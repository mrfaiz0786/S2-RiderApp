export function isRouteName(value: unknown): value is RouteName {
  return typeof value === "string" && routes.some((route) => route.name === value);
}
export function getRoute(name: RouteName) {
  const route = routes.find((item) => item.name === name);
  if (!route) throw new Error("Unknown route: " + name);
  return route;
}
export function defaultBackRoute(name: RouteName): RouteName {
  const index = routes.findIndex((route) => route.name === name);
  return getRoute(name).group === "Onboarding" ? routes[Math.max(0, index - 1)].name : "home";
}
