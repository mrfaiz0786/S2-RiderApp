import type { HttpMethod } from "./types";
export type ApiOperation = {
  method: HttpMethod;
  path: string;
  authenticated: boolean;
  requiresIdempotencyKey: boolean;
  area: string;
  purpose: string;
  requestFields: string;
  responseFields: string;
  priority: "required" | "conditional";
};
function op(
  method: HttpMethod,
  path: string,
  authenticated: boolean,
  requiresIdempotencyKey: boolean,
  area: string,
  purpose: string,
  requestFields: string,
  responseFields: string,
  priority: ApiOperation["priority"] = "required",
): ApiOperation {
  return {
    method,
    path,
    authenticated,
    requiresIdempotencyKey,
    area,
    purpose,
    requestFields,
    responseFields,
    priority,
  };
}
