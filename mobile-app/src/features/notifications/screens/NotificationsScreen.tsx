import { useNotifications } from "@/features/notifications/model";
import { useDelivery } from "@/features/delivery/model";
import { useNavigation } from "@/navigation/NavigationProvider";
import { journeyStyles as s } from "@/shared/theme/journeyStyles";
import { BrandButton } from "@/shared/ui/BrandButton";
import { Card } from "@/shared/ui/Card";
import { ScreenHero } from "@/shared/ui/ScreenHero";
import { Text } from "react-native";
export function NotificationsScreen() {
  const { notifications, notificationRead, setNotificationRead } = useNotifications();
  const { order, status } = useDelivery();
  const { navigate } = useNavigation();
  return (
    <>
      <ScreenHero
        eyebrow="TEST RIDER UPDATES"
        title="Notifications"
        subtitle="Generated by your test orders and completed deliveries, not static sample messages."
        icon="bell-outline"
      />
      <Text style={s.body}>
        {notifications.filter((item) => !notificationRead.includes(item.id)).length} unread
      </Text>
      <BrandButton
        title="Mark all as read"
        secondary
        disabled={!notifications.length}
        onPress={() => setNotificationRead(notifications.map((item) => item.id))}
      />
      {!notifications.length ? (
        <Card>
          <Text style={s.body}>
            Go online from Home to receive your first test order notification.
          </Text>
        </Card>
      ) : null}
      {notifications.map((item) => (
        <Card key={item.id} tone={notificationRead.includes(item.id) ? undefined : "blue"}>
          <Text style={s.heading}>{item.title}</Text>
          <Text style={s.body}>{item.body}</Text>
          <Text style={s.small}>
            {new Date(item.at).toLocaleString()} ·{" "}
            {notificationRead.includes(item.id) ? "Read" : "Unread"}
          </Text>
          <BrandButton
            title={item.kind === "completed" ? "View in history" : "Open order update"}
            secondary
            onPress={() => {
              setNotificationRead((previous) => [...previous, item.id]);
              navigate(
                item.kind === "completed" ||
                  item.orderId !== order?.id ||
                  ["completed", "expired", "declined"].includes(status)
                  ? "history"
                  : status === "offered"
                    ? "offers"
                    : "active-job",
              );
            }}
          />
        </Card>
      ))}
    </>
  );
}
